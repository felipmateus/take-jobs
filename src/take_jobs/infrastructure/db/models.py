"""SQLAlchemy table definitions. The DDL itself is owned by `migrations/versions/0001_*`."""

from datetime import datetime

from sqlalchemy import BigInteger, Computed, ForeignKey, Identity, Integer, String, Text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from sqlalchemy.types import DateTime


class Base(DeclarativeBase):
    pass


class JobRow(Base):
    __tablename__ = "jobs"

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    source: Mapped[str] = mapped_column(String(32))
    external_id: Mapped[str] = mapped_column(String(64))
    title: Mapped[str] = mapped_column(Text)
    company: Mapped[str | None] = mapped_column(Text)
    location: Mapped[str | None] = mapped_column(Text)
    description: Mapped[str | None] = mapped_column(Text)
    published_label: Mapped[str | None] = mapped_column(Text)
    url: Mapped[str] = mapped_column(Text)
    seniority: Mapped[str | None] = mapped_column(String(8))
    first_seen_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    last_seen_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # Generated by PostgreSQL (ADR-005); never written by the application.
    search_text: Mapped[str] = mapped_column(
        Text,
        Computed(
            "immutable_unaccent(lower("
            "title || ' ' || coalesce(company, '') || ' ' || coalesce(description, '')"
            "))",
            persisted=True,
        ),
    )


class CollectionRunRow(Base):
    __tablename__ = "collection_runs"

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    trigger: Mapped[str] = mapped_column(String(16))
    status: Mapped[str] = mapped_column(String(16))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    error: Mapped[str | None] = mapped_column(Text)
    expected_combinations: Mapped[int] = mapped_column(Integer)


class CollectionRunResultRow(Base):
    __tablename__ = "collection_run_results"

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    run_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("collection_runs.id", ondelete="CASCADE")
    )
    source: Mapped[str] = mapped_column(String(32))
    term: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(8))
    pages: Mapped[int] = mapped_column(Integer)
    new_count: Mapped[int] = mapped_column(Integer)
    seen_again_count: Mapped[int] = mapped_column(Integer)
    discarded_count: Mapped[int] = mapped_column(Integer)
    error: Mapped[str | None] = mapped_column(Text)
